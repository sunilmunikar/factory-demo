/**
 * Turn arbitrary text into a URL-safe slug: lowercase ASCII letters and digits
 * separated by single hyphens, with no leading or trailing hyphen.
 */
export function slugify(input: string): string {
  return input
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}
